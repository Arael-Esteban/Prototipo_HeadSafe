"""Embed only explicitly allowlisted offline resources as deterministic gzip."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path, PurePosixPath
ROOT=Path(__file__).resolve().parents[1]

def generate(web,manifest,output):
    web=web.resolve()
    entries=json.loads(manifest.read_text(encoding='utf-8'))
    chunks=['// Generated by tools/embed-web.py; do not edit.\n#pragma once\n#include <Arduino.h>\n',
            'struct WebAsset { const char* path; const char* mime; const uint8_t* data; size_t size; };\n']
    rows=[]; urls=set(); total=0
    for i,entry in enumerate(entries):
        path=entry['path']; url=entry['url']; mime=entry['mime']
        relative=PurePosixPath(path)
        if relative.is_absolute() or '..' in relative.parts or '\\' in path or ':' in path:
            raise ValueError('Asset path must stay within web root: '+path)
        source=(web/path).resolve()
        if not source.is_relative_to(web): raise ValueError('Asset escaped web root')
        if not url.startswith('/') or url.startswith('//') or '?' in url or '#' in url or url in urls:
            raise ValueError('Invalid or duplicate asset URL: '+url)
        if not mime or any(ord(c)<32 for c in mime): raise ValueError('Invalid MIME')
        urls.add(url)
        raw=source.read_bytes(); compressed=gzip.compress(raw,compresslevel=9,mtime=0)
        # Normalize gzip OS byte too: Python implementations differ across platforms.
        compressed=compressed[:9]+b'\xff'+compressed[10:]
        total+=len(compressed)
        chunks.append(f'// {path} sha256={hashlib.sha256(raw).hexdigest()} raw={len(raw)} gzip={len(compressed)}\n')
        chunks.append(f'static const uint8_t WEB_ASSET_{i}[] PROGMEM = {{\n')
        chunks.extend('  '+','.join(f'0x{v:02x}' for v in compressed[j:j+24])+',\n' for j in range(0,len(compressed),24))
        chunks.append('};\n')
        rows.append(f'  {{{json.dumps(url)},{json.dumps(mime)},WEB_ASSET_{i},sizeof(WEB_ASSET_{i})}},\n')
        if url=='/': rows.append(f'  {{"/index.html",{json.dumps(mime)},WEB_ASSET_{i},sizeof(WEB_ASSET_{i})}},\n')
    chunks.append('static const WebAsset WEB_ASSETS[] PROGMEM = {\n'+''.join(rows)+'};\n')
    chunks.append('static constexpr size_t WEB_ASSET_COUNT=sizeof(WEB_ASSETS)/sizeof(WEB_ASSETS[0]);\n')
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(''.join(chunks),encoding='utf-8',newline='\n')
    print(f'Embedded {len(entries)} allowlisted resources, {total} gzip bytes: {output}')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--web-dir',type=Path,default=ROOT)
    parser.add_argument('--manifest',type=Path,default=ROOT/'firmware/web-assets.json')
    parser.add_argument('--output',type=Path,default=ROOT/'firmware/HeadSafe/web_assets.h')
    args=parser.parse_args()
    generate(args.web_dir,args.manifest,args.output)
if __name__=='__main__': main()
